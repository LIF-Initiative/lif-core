-- Issue #1182: the control plane's developer-key table (ADR 0006, ADR 0008).
--
-- One table for every workspace's keys. "Workspace" is the tenant schema name, kept as an opaque
-- string (ADR 0008 decision 2), and "OwnerSub" is the caller's Cognito `sub` (decision 1). Only the
-- key's SHA-256 hash is stored, and it is unique, because a validator of an opaque key looks it up
-- by hash (ADR 0006 decision 3). The column types follow MDR's table (V1.5) so #1183 can copy rows
-- across, except "Id", which is new here: the copy gives rows new ids (ADR 0006 decision 4).
--
-- Idempotent, so it can be re-applied safely (see README.md).

CREATE TABLE IF NOT EXISTS "DeveloperApiKeys" (
    "Id"             integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Workspace"      varchar     NOT NULL,
    "OwnerSub"       varchar     NOT NULL,
    "Label"          varchar     NOT NULL,
    "KeyPrefix"      varchar     NOT NULL,
    "KeyHash"        varchar     NOT NULL,
    "CreationDate"   timestamptz NOT NULL DEFAULT now(),
    "LastUsedDate"   timestamptz,
    "RevokedDate"    timestamptz,
    "ExpirationDate" timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS "ux_DeveloperApiKeys_KeyHash" ON "DeveloperApiKeys" ("KeyHash");
CREATE INDEX IF NOT EXISTS "ix_DeveloperApiKeys_Workspace_OwnerSub" ON "DeveloperApiKeys" ("Workspace", "OwnerSub");
